class Solution:
    def countMajoritySubarrays(self, nums: list[int], target: int) -> int:
        n = len(nums)

        ans = 0

        for i in range(n):
            c = 0
            for j in range(i, n):
                c += 1 if nums[j] == target else -1
                if c > 0:
                    ans += 1

        return ans


def test():
    assert Solution().countMajoritySubarrays(nums=[1, 2, 2, 3], target=2) == 5
    assert Solution().countMajoritySubarrays(nums=[1, 1, 1, 1], target=1) == 10
    assert Solution().countMajoritySubarrays(nums=[1, 2, 3], target=4) == 0


